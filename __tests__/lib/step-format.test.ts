import { describe, expect, it } from "vitest";

import { formatCoinQty, formatPrice, roundToStep } from "@/lib/format";

/** U+2212 MINUS SIGN. 음수 부호로 ASCII `-`(U+002D) 대신 쓴다. */
const MINUS = "\u2212";
/** U+2014 EM DASH. 값이 없는 표시. */
const EM_DASH = "\u2014";

describe("단위 반올림과 가격·수량 표시 — 값을 틱·수량 단위에 맞춰 Bybit와 같은 규칙으로 본다", () => {
  describe("단위의 배수로 내리기·올리기", () => {
    /**
     * @spec DoD-3
     * @given 배수가 아닌 표본을 "down"으로 하나씩 넣는다: 양수 (0.0015, 0.001) → 0.001, (0.25, 0.1) → 0.2, (0.079, 0.01) → 0.07, (0.2005, 0.001) → 0.2, (0.00019, 0.001) → 0, (60274.37, 0.1) → 60274.3 / 허용치 밖의 작은 차이 (0.00199999999999, 0.001) → 0.001 / 음수 (−0.0015, 0.001) → −0.002, (−0.25, 0.1) → −0.3
     * @when 값을 step의 배수로 "down" 반올림한다
     * @then 결과가 value 이하인 step의 배수 중 가장 큰 값(−∞ 방향)이며 표본의 기대값과 === 비교로 정확히 같다
     * @then 허용치(단위 수 value ÷ step과 가장 가까운 정수의 차가 1e-12 × max(1, |value ÷ step|) 이하) 밖의 차이는 실제 차이로 다룬다((0.00199999999999, 0.001)의 단위 수 1.99999999999는 2와의 차 1e-11이 허용치 1.99999999999e-12보다 커서 0.001이며 0.002가 아니다)
     */
    it("[DoD-3] down은 value 이하인 step의 배수 중 가장 큰 값을 오차 없이 돌려준다", () => {
      const cases: [value: number, step: number, expected: number][] = [
        [0.0015, 0.001, 0.001],
        [0.25, 0.1, 0.2],
        [0.079, 0.01, 0.07],
        [0.2005, 0.001, 0.2],
        [0.00019, 0.001, 0],
        [60274.37, 0.1, 60274.3],
        // 허용치 밖의 작은 차이: 단위 수 1.99999999999는 2와의 차 1e-11 > 허용치 1.99999999999e-12
        [0.00199999999999, 0.001, 0.001],
        [-0.0015, 0.001, -0.002],
        [-0.25, 0.1, -0.3],
      ];
      for (const [value, step, expected] of cases) {
        expect(roundToStep(value, step, "down"), `(${value}, ${step}, "down")`).toBe(expected);
      }
    });

    /**
     * @spec DoD-3
     * @given 배수가 아닌 표본을 "up"으로 하나씩 넣는다: 양수 (0.0015, 0.001) → 0.002, (0.25, 0.1) → 0.3, (0.071, 0.01) → 0.08, (0.2005, 0.001) → 0.201, (0.00019, 0.001) → 0.001 / 허용치 밖의 작은 차이 (0.00100000000001, 0.001) → 0.002 / 음수 (−0.0015, 0.001) → −0.001, (−0.25, 0.1) → −0.2
     * @when 값을 step의 배수로 "up" 반올림한다
     * @then 결과가 value 이상인 step의 배수 중 가장 작은 값(+∞ 방향)이며 표본의 기대값과 === 비교로 정확히 같다((0.25, 0.1) → 0.3이며 0.30000000000000004가 아니다)
     * @then 허용치(단위 수 value ÷ step과 가장 가까운 정수의 차가 1e-12 × max(1, |value ÷ step|) 이하) 밖의 차이는 실제 차이로 다룬다((0.00100000000001, 0.001)의 단위 수 1.00000000001은 1과의 차 1e-11이 허용치 1.00000000001e-12보다 커서 0.002이며 0.001이 아니다)
     */
    it("[DoD-3] up은 value 이상인 step의 배수 중 가장 작은 값을 오차 없이 돌려준다", () => {
      const cases: [value: number, step: number, expected: number][] = [
        [0.0015, 0.001, 0.002],
        [0.25, 0.1, 0.3],
        [0.071, 0.01, 0.08],
        [0.2005, 0.001, 0.201],
        [0.00019, 0.001, 0.001],
        // 허용치 밖의 작은 차이: 단위 수 1.00000000001은 1과의 차 1e-11 > 허용치 1.00000000001e-12
        [0.00100000000001, 0.001, 0.002],
        [-0.0015, 0.001, -0.001],
        [-0.25, 0.1, -0.2],
      ];
      for (const [value, step, expected] of cases) {
        expect(roundToStep(value, step, "up"), `(${value}, ${step}, "up")`).toBe(expected);
      }
    });

    /**
     * @spec DoD-3
     * @given 이미 step의 배수인 오차 경계 표본을 "up"과 "down" 각각으로 하나씩 넣는다: (0.3, 0.1) SOL 수량 단위, (0.07, 0.01) ETH 수량 단위, (0.003, 0.001) BTC 수량 단위, (0.29, 0.01), (0.2, 0.001), (60274.3, 0.1), 큰 배수 (262.441, 0.001) BTC 수량 단위(단위 수 262440.99999999994, 정수보다 조금 작음), (512.003, 0.001) BTC 수량 단위(단위 수 512003.00000000006, 정수보다 조금 큼), (30000.3, 0.1) SOL 수량 단위, (26214.6, 0.1) SOL 수량 단위(단위 수 262145.99999999994), 음수 (−0.3, 0.1), (−0.07, 0.01)
     * @when 값을 step의 배수로 반올림한다
     * @then 두 모드 모두 결과가 입력 value와 === 비교로 정확히 같다(예: roundToStep(0.3, 0.1, "down") === 0.3이며 0.2가 아니고, roundToStep(0.07, 0.01, "up") === 0.07이며 0.08이 아니다)
     * @then 허용치(단위 수 value ÷ step과 가장 가까운 정수의 차가 1e-12 × max(1, |value ÷ step|) 이하) 안의 차이는 부동소수점 오차로 보고 그 정수 배로 본다(JS에서 262.441 ÷ 0.001 = 262440.99999999994이지만 roundToStep(262.441, 0.001, "down") === 262.441이며 262.44가 아니다)
     */
    it("[DoD-3] 이미 step의 배수인 값은 up·down 모두 그대로 돌려준다", () => {
      const cases: [value: number, step: number][] = [
        [0.3, 0.1],
        [0.07, 0.01],
        [0.003, 0.001],
        [0.29, 0.01],
        [0.2, 0.001],
        [60274.3, 0.1],
        // 큰 배수: 단위 수가 정수와 허용치 안에서 다르다
        [262.441, 0.001], // 262440.99999999994 (정수보다 조금 작음)
        [512.003, 0.001], // 512003.00000000006 (정수보다 조금 큼)
        [30000.3, 0.1],
        [26214.6, 0.1], // 262145.99999999994
        [-0.3, 0.1],
        [-0.07, 0.01],
      ];
      for (const [value, step] of cases) {
        for (const mode of ["up", "down"] as const) {
          expect(roundToStep(value, step, mode), `(${value}, ${step}, "${mode}")`).toBe(value);
        }
      }
    });
  });

  describe("반올림할 수 없는 값", () => {
    /**
     * @spec EC-6
     * @given 수가 아닌 value 표본을 step 0.001과 "up"·"down" 각각으로 하나씩 넣는다: null, NaN, Infinity, −Infinity
     * @when 값을 step의 배수로 반올림한다
     * @then 모든 결과가 null이다
     */
    it("[EC-6] value가 null·NaN·Infinity·-Infinity이면 null을 돌려준다", () => {
      for (const value of [null, Number.NaN, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY]) {
        for (const mode of ["up", "down"] as const) {
          expect(roundToStep(value, 0.001, mode), `(${value}, 0.001, "${mode}")`).toBeNull();
        }
      }
    });
  });

  describe("가격 표시", () => {
    /**
     * @spec DoD-4
     * @given 가격 표본을 하나씩 넣는다: 양수 (60274, 2) → "60,274.00", (60274.3, 2) → "60,274.30", (1234567.8, 2) → "1,234,567.80", (150.12, 3) → "150.120", (999.5, 3) → "999.500" / 음수 (−60274, 2) → "−60,274.00", (−1234.5, 2) → "−1,234.50", (−150.12, 3) → "−150.120" (음수 기대 문자열의 부호는 U+2212)
     * @when 가격을 priceScale 자릿수로 표시한다
     * @then 결과 문자열이 표본의 기대 문자열과 코드 포인트 단위로 정확히 같다(priceScale 자릿수까지 0을 채운 소수, 세 자리마다 쉼표, 뒤에 " USDT" 등 단위 없음)
     * @then 음수 가격의 부호는 앞에 붙은 U+2212 "−"이며 ASCII "-"(U+002D)가 아니다
     */
    it("[DoD-4] 가격은 priceScale 소수 자릿수와 천 단위 구분, 음수 부호 U+2212 '−'로, 단위 없이 표시한다", () => {
      const cases: [value: number, priceScale: number, expected: string][] = [
        [60274, 2, "60,274.00"],
        [60274.3, 2, "60,274.30"],
        [1234567.8, 2, "1,234,567.80"],
        [150.12, 3, "150.120"],
        [999.5, 3, "999.500"],
        [-60274, 2, `${MINUS}60,274.00`],
        [-1234.5, 2, `${MINUS}1,234.50`],
        [-150.12, 3, `${MINUS}150.120`],
      ];
      for (const [value, priceScale, expected] of cases) {
        const shown = formatPrice(value, priceScale);
        expect(shown, `(${value}, ${priceScale})`).toBe(expected);
        // 음수 부호는 U+2212이며 ASCII "-"(U+002D)는 없다
        expect(shown, `(${value}, ${priceScale})`).not.toContain("-");
      }
    });

    /**
     * @spec DoD-5
     * @given priceScale보다 소수 자릿수가 많은 표본을 하나씩 넣는다: 양수 버림 (60274.379, 2) → "60,274.37"(사사오입이면 60,274.38), (150.1239, 3) → "150.123" / 음수 0 방향 버림 (−60274.379, 2) → "−60,274.37"(floor인 "−60,274.38"이 아니다) / 오차 정리 후 버림 JS `100.35 - 100` 결과 (0.3499999999999943, 2) → "0.35", (−0.3499999999999943, 2) → "−0.35" / 정리 자릿수 10 고정 (1.2399999999, 2)(소수 10자리) → "1.23", (1.23999999999, 2)(소수 11자리) → "1.24" (음수 부호는 U+2212)
     * @when 가격을 priceScale 자릿수로 표시한다
     * @then 결과 문자열이 표본의 기대 문자열과 코드 포인트 단위로 정확히 같다(원값을 소수 10자리에서 사사오입한 뒤 priceScale 자릿수에서 0 방향으로 버린 값)
     */
    it("[DoD-5] priceScale보다 긴 가격은 소수 10자리에서 오차를 정리한 뒤 0 방향으로 버려 표시한다", () => {
      const cases: [value: number, priceScale: number, expected: string][] = [
        // 양수 버림: 사사오입이면 60,274.38
        [60274.379, 2, "60,274.37"],
        [150.1239, 3, "150.123"],
        // 음수 0 방향 버림: floor라면 −60,274.38
        [-60274.379, 2, `${MINUS}60,274.37`],
        // 오차 정리 후 버림: JS `100.35 - 100`의 결과
        [0.3499999999999943, 2, "0.35"],
        [-0.3499999999999943, 2, `${MINUS}0.35`],
        // 정리 자릿수 10 고정: 9자리 이하로 정리하면 1.24, 11자리 이상으로 정리하면 1.23
        [1.2399999999, 2, "1.23"],
        [1.23999999999, 2, "1.24"],
      ];
      for (const [value, priceScale, expected] of cases) {
        expect(formatPrice(value, priceScale), `(${value}, ${priceScale})`).toBe(expected);
      }
    });
  });

  describe("값이 없는 가격", () => {
    /**
     * @spec EC-7
     * @given 값이 없는(null) 가격을 priceScale 2와 3으로 각각 넣는다
     * @when 가격을 priceScale 자릿수로 표시한다
     * @then 결과 문자열이 정확히 U+2014 "—" 한 글자다
     */
    it("[EC-7] 값이 없는 가격은 U+2014 '—'로 표시한다", () => {
      expect(formatPrice(null, 2)).toBe(EM_DASH);
      expect(formatPrice(null, 3)).toBe(EM_DASH);
    });
  });

  describe("코인 수량 표시", () => {
    /**
     * @spec DoD-6
     * @given qtyStep 자릿수보다 짧거나 같은 수량 표본을 하나씩 넣는다: (0.2, 0.001) → "0.200", (0.003, 0.001) → "0.003", (0.07, 0.01) → "0.07", (0.5, 0.01) → "0.50", (0.3, 0.1) → "0.3", (2, 0.1) → "2.0"
     * @when 코인 수량을 qtyStep 자릿수로 표시한다
     * @then 결과 문자열이 표본의 기대 문자열과 정확히 같다(qtyStep 0.001 → 소수 3자리, 0.01 → 2자리, 0.1 → 1자리까지 끝의 0을 채운다)
     */
    it("[DoD-6] 코인 수량은 qtyStep의 소수 자릿수로 끝의 0을 채워 표시한다", () => {
      const cases: [value: number, qtyStep: number, expected: string][] = [
        [0.2, 0.001, "0.200"],
        [0.003, 0.001, "0.003"],
        [0.07, 0.01, "0.07"],
        [0.5, 0.01, "0.50"],
        [0.3, 0.1, "0.3"],
        [2, 0.1, "2.0"],
      ];
      for (const [value, qtyStep, expected] of cases) {
        expect(formatCoinQty(value, qtyStep), `(${value}, ${qtyStep})`).toBe(expected);
      }
    });

    /**
     * @spec DoD-6
     * @given qtyStep 자릿수보다 긴 수량 표본을 하나씩 넣는다: 0 방향 버림 (0.0019, 0.001) → "0.001"(사사오입이면 0.002), (0.0015, 0.001) → "0.001", (0.079, 0.01) → "0.07", (0.25, 0.1) → "0.2" / 오차 정리 후 버림 (6.999999999999999, 0.001) → "7.000", JS `100.35 - 100` 결과 (0.3499999999999943, 0.01) → "0.35" / 정리 자릿수 10 고정 (1.2399999999, 0.01)(소수 10자리) → "1.23", (1.23999999999, 0.01)(소수 11자리) → "1.24"
     * @when 코인 수량을 qtyStep 자릿수로 표시한다
     * @then 결과 문자열이 표본의 기대 문자열과 정확히 같다(원값을 소수 10자리에서 사사오입한 뒤 qtyStep 자릿수에서 0 방향으로 버린 값)
     */
    it("[DoD-6] qtyStep보다 긴 코인 수량은 소수 10자리에서 오차를 정리한 뒤 0 방향으로 버려 표시한다", () => {
      const cases: [value: number, qtyStep: number, expected: string][] = [
        // 0 방향 버림: 사사오입이면 0.002
        [0.0019, 0.001, "0.001"],
        [0.0015, 0.001, "0.001"],
        [0.079, 0.01, "0.07"],
        [0.25, 0.1, "0.2"],
        // 오차 정리 후 버림
        [6.999999999999999, 0.001, "7.000"],
        // JS `100.35 - 100`의 결과
        [0.3499999999999943, 0.01, "0.35"],
        // 정리 자릿수 10 고정
        [1.2399999999, 0.01, "1.23"],
        [1.23999999999, 0.01, "1.24"],
      ];
      for (const [value, qtyStep, expected] of cases) {
        expect(formatCoinQty(value, qtyStep), `(${value}, ${qtyStep})`).toBe(expected);
      }
    });
  });
});
